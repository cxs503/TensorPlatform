"""战役成熟化整合门（maturity gate）= 判据 → 证据 → 台账 → 契约 → 报告 的通用闭环。

为什么存在
----------
战役 DAG 收尾节点（如 ``p54w3-n08-maturity-integration``）要求「上游节点判据 ≥80% 通过、
跨仓集成全绿、能力台账与节点一一对应、接口契约完整、总结报告六要素齐全」。这类要求
过去只能靠人读报告 + 手抄数字，于是「测试绿 ≠ 数字对」「报告写了 = 能力有了」反复发生。
本包把它拆成四个**可机器复算**的环节：

=============  ==========================================  ==========================
环节           代码                                        判据
=============  ==========================================  ==========================
规格           :mod:`.spec`                              判据/阈值/证据路径全部工件化
证据           :mod:`.evidence`                          值可复算 + 钉桩 + 自述互裁
裁定           :mod:`.gate`                              PASS/FAIL/WITHHELD 三值
台账           :mod:`.ledger`                            节点 ↔ 条目双向双射
契约           :mod:`.contracts`                         文档必含项/端点覆盖率
报告           :mod:`.report`                            六要素 + 图表 + 数字溯源
=============  ==========================================  ==========================

与既有 maturity 机制的分界（避免重复造轮子，检索记录）
-----------------------------------------------------
* ``scripts/maturity_gate.py``：**平台模块** maturity 标签的证据门（``quality/maturity/policy.json``
  驱动、模块级 beta/alpha 标签、仓内不可变产物 sha256）。解决「这个模块自称 beta 有没有证据」。
* ``tools/criteria_governance/maturity.py``：判据治理的四维成熟度评分（覆盖率/可派生率/漂移/假阳性）。
  解决「判据集本身治理得怎么样」。
* **本包**：**战役节点交付**的整合裁定——跨仓（多仓库工作树）证据 → 判据通过率 → 三值裁定 →
  能力台账双射 → 接口契约完整性 → 六要素报告。解决「这一波上游节点到底能交付什么」。
  前两者不覆盖跨仓证据解析、复合判据合取、台账双射与契约/报告机器校验，故不重写它们，
  只在其上补「战役层」。

边界（铁律）
------------
**零领域语义**：本包代码里没有、也不允许出现任何学科词条、域判据或算例常量。
所有战役内容来自 ``data/maturity_gate/*.spec.json`` 与证据文档工件；测试夹具用合成域。
"""

