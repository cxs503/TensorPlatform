"""计算调度看板 + 机器门：队列深度 / 放置分布 / 等待分位 / 违例数。

三类消费者：
  1. **人**：``render_markdown`` 出一段 PANORAMA 可直接注入的块（带标记，幂等注入）；
  2. **机器门**：``evaluate`` 出 pass / fail / insufficient_data（可以红、必须能失败）；
  3. **报告**：``metrics`` 是纯 JSON（零手抄，报告里的数字全部从这里取）。

违例（violations）不是装饰：blocking 级违例会直接把门判 fail。
"""
from __future__ import annotations

import datetime as _dt
from typing import Any, Iterable

from tools.compute_meter.meter import (
    audit_running as meter_audit_running,
    percentile,
    per_mission,
    summarize,
)
from tools.compute_meter.policy import (
    V_HEAVY_ON_CONTROL,
    V_LOCAL_SHARE_OVER_TARGET,
    V_QUEUE_HOL,
    V_STALE_RUNNING,
    V_UNGOVERNED,
    Policy,
)

BEGIN = "<!-- COMPUTE-POLICY:BEGIN (generated by tools/compute_meter/dashboard.py) -->"
END = "<!-- COMPUTE-POLICY:END -->"

SEVERITY_BLOCKING = "blocking"


def _secs(v: Any) -> float | None:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f


def _parse_ts(v: Any) -> _dt.datetime | None:
    """时间戳解析（宽容：psql 的 ``+00`` 无冒号时区也认），失败返回 None。"""
    if v in (None, ""):
        return None
    try:
        from tools.compute_meter.meter import _ts
        return _ts(v)
    except Exception:
        return None


def queue_metrics(cluster_rows: Iterable[dict], *, now: _dt.datetime | None = None,
                  recent_dispatch_seconds: float = 3600.0,
                  hol_warn_seconds: float = 3600.0) -> dict:
    """队列深度 / 等待分位 / 近期派发活跃度（数据源：cluster_jobs 调度账本）。"""
    rows = list(cluster_rows)
    now = now or _dt.datetime.now(_dt.timezone.utc)
    waits: list[float] = []
    queued_waits: list[float] = []
    for r in rows:
        sub, start = _parse_ts(r.get("submitted_at")), _parse_ts(r.get("started_at"))
        if sub and start:
            waits.append(max((start - sub).total_seconds(), 0.0))
        if r.get("state") == "queued" and sub:
            queued_waits.append(max((now - sub).total_seconds(), 0.0))
    by_state: dict[str, int] = {}
    for r in rows:
        st = str(r.get("state") or "-")
        by_state[st] = by_state.get(st, 0) + 1
    # 近 1h 是否真有派发动作（按 started_at 计，而不是按等待时长）
    recent = [1 for r in rows
              if (st := _parse_ts(r.get("started_at"))) is not None
              and (now - st).total_seconds() <= recent_dispatch_seconds]
    oldest = max(queued_waits) if queued_waits else 0.0
    return {
        "depth": by_state.get("queued", 0),
        "running": by_state.get("running", 0),
        "terminal": sum(v for k, v in by_state.items()
                        if k in ("succeeded", "failed", "killed", "shards")),
        "by_state": by_state,
        "oldest_queued_wait_seconds": round(oldest, 1),
        "wait_n": len(waits),
        "wait_p50_seconds": percentile(waits, 50),
        "wait_p90_seconds": percentile(waits, 90),
        "wait_p99_seconds": percentile(waits, 99),
        "wait_max_seconds": round(max(waits), 1) if waits else None,
        "dispatched_last_hour": len(recent),
        # 排空时间估算：队列深度 / 近 1h 派发速率（速率 0 → None，说明彻底停摆）
        "drain_hours_estimate": (round(by_state.get("queued", 0) / len(recent), 1)
                                 if recent else None),
        "terminal_last_hour": sum(
            1 for r in rows
            if (st := _parse_ts(r.get("finished_at"))) is not None
            and (now - st).total_seconds() <= recent_dispatch_seconds),
        "hol_threshold_seconds": float(hol_warn_seconds),
        "hol_suspect": bool(oldest > hol_warn_seconds and by_state.get("queued", 0) > 0
                            and len(recent) == 0),   # 有队无人派 → 队头阻塞
    }


def violation_metrics(records: Iterable[dict], policy: Policy,
                      *, queue: dict | None = None) -> list[dict]:
    """从账本 + 队列事实里认定违例（每条都带证据 source_ref）。"""
    recs = list(records)
    out: list[dict] = []
    heavy_local = []
    ungoverned = 0
    for r in recs:
        cpu = float(r.get("cpu_seconds") or 0.0)
        cls = policy.cls(r.get("priority_class"))
        if r.get("placement") == "local" and cpu >= cls.heavy_threshold_cpu_seconds:
            heavy_local.append((r.get("source_ref"), round(cpu, 1),
                                r.get("mission_id"), cls.name))
        if not r.get("policy_version"):
            ungoverned += 1
    if heavy_local:
        out.append({
            "code": V_HEAVY_ON_CONTROL, "severity": SEVERITY_BLOCKING,
            "count": len(heavy_local),
            "detail": (f"{len(heavy_local)} 条本机账本行的实测 CPU 秒超过其优先级类重计算阈值"
                       f"（99 控制节点不该跑重活）"),
            "evidence": heavy_local[:10],
        })
    summary = summarize(recs)
    target = policy.local_share_target
    if summary["total_cpu_seconds"] > 0 and summary["local_share"] > target:
        out.append({
            "code": V_LOCAL_SHARE_OVER_TARGET, "severity": SEVERITY_BLOCKING,
            "count": 1,
            "detail": (f"本机占比 {summary['local_share']:.2%} > 目标 {target:.0%}"
                       f"（local={summary['by_placement']['local']['cpu_seconds']}s / "
                       f"total={summary['total_cpu_seconds']}s）"),
            "evidence": [],
        })
    if ungoverned:
        out.append({
            "code": V_UNGOVERNED, "severity": "warn", "count": ungoverned,
            "detail": f"{ungoverned}/{len(recs)} 条账本行无 policy_version（未经策略引擎的野生计算）",
            "evidence": [r.get("source_ref") for r in recs if not r.get("policy_version")][:10],
        })
    if queue and queue.get("stale", {}).get("stale"):
        st = queue["stale"]["stale"]
        out.append({
            "code": V_STALE_RUNNING, "severity": SEVERITY_BLOCKING, "count": len(st),
            "detail": (f"{len(st)} 条 running 行超过 timeout×{policy.stale_after_factor:g} 仍标在跑 → "
                       f"并发帽被僵尸行占满（准入饥饿）"),
            "evidence": [s_["id"] for s_ in st[:10]],
        })
    if queue and queue.get("hol_suspect"):
        out.append({
            "code": V_QUEUE_HOL, "severity": SEVERITY_BLOCKING, "count": 1,
            "detail": (f"队列深度 {queue['depth']}，最老排队 {queue['oldest_queued_wait_seconds']:.0f}s，"
                       f"近 1h 无新派发 → 疑似队头阻塞（FIFO+固定批量的派发饥饿）"),
            "evidence": [],
        })
    return out


def metrics(records: Iterable[dict], cluster_rows: Iterable[dict] | None, policy: Policy,
            *, now: _dt.datetime | None = None) -> dict:
    recs = list(records)
    summary = summarize(recs)
    rows = list(cluster_rows or [])
    q = queue_metrics(rows, now=now)
    q["stale"] = meter_audit_running(rows, now=now, factor=policy.stale_after_factor)
    viol = violation_metrics(recs, policy, queue=q)
    return {
        "generated_at": (now or _dt.datetime.now(_dt.timezone.utc)).isoformat(),
        "policy_version": policy.version,
        "local_share_target": policy.local_share_target,
        "summary": summary,
        "queue": q,
        "violations": viol,
        "violation_counts": _count_by(viol),
        "per_mission": per_mission(recs)[:20],
        "mission_count": len(per_mission(recs)),
        "governed_rows": sum(1 for r in recs if r.get("policy_version")),
    }


def _count_by(viol: list[dict]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for v in viol:
        e = out.setdefault(v["code"], {"count": 0, "severity": v["severity"]})
        e["count"] += int(v.get("count") or 0)
    return out


# ── 机器门 ────────────────────────────────────────────────────────────
PASS, FAIL, INSUFFICIENT = "pass", "fail", "insufficient_data"
EXIT = {PASS: 0, FAIL: 3, INSUFFICIENT: 4}


SHARE_CODES = (V_HEAVY_ON_CONTROL, V_LOCAL_SHARE_OVER_TARGET)
HYGIENE_CODES = (V_STALE_RUNNING, V_QUEUE_HOL, V_UNGOVERNED)


def evaluate(m: dict, *, target: float | None = None, min_cpu_seconds: float = 600.0,
             require_governed: bool = True, scope: str = "all") -> dict:
    """门判据（先于动手声明，事后不许改）：本机占比 ≤ 目标 且 无 blocking 违例。

    - 证据不足（总 CPU 秒 < min_cpu_seconds，或账本全是无 policy_version 的野生行）
      → insufficient_data（exit 4），绝不拿小样本吹 pass；
    - 超目标或有 blocking 违例 → fail（exit 3）。
    """
    tgt = m["local_share_target"] if target is None else float(target)
    reasons: list[str] = []
    total = float(m["summary"]["total_cpu_seconds"])
    if total < min_cpu_seconds:
        reasons.append(f"证据不足：账本总 CPU {total:g}s < 门槛 {min_cpu_seconds:g}s")
    if require_governed and m.get("governed_rows", 0) == 0:
        reasons.append("证据不足：账本无一行带 policy_version（策略引擎从未参与放置）")
    if reasons:
        return {"verdict": INSUFFICIENT, "exit_code": EXIT[INSUFFICIENT],
                "reasons": reasons, "local_share": m["summary"]["local_share"],
                "target": tgt, "blocking": []}
    codes = {"share": SHARE_CODES, "hygiene": HYGIENE_CODES}.get(scope)
    blocking = [v for v in m["violations"] if v["severity"] == SEVERITY_BLOCKING
                and (codes is None or v["code"] in codes)]
    share = float(m["summary"]["local_share"])
    if share > tgt:
        reasons.append(f"本机占比 {share:.2%} 超目标 {tgt:.0%}")
    for v in blocking:
        reasons.append(f"违例 {v['code']}×{v.get('count')}: {v['detail']}")
    verdict = FAIL if reasons else PASS
    return {"verdict": verdict, "exit_code": EXIT[verdict], "reasons": reasons,
            "scope": scope, "local_share": share, "target": tgt,
            "blocking": [v["code"] for v in blocking]}


# ── 渲染 ──────────────────────────────────────────────────────────────
def _fmt_pct(v: Any) -> str:
    return "—" if v is None else f"{float(v) * 100:.1f}%"


def _fmt_s(v: Any) -> str:
    f = _secs(v)
    if f is None:
        return "—"
    return f"{f:.0f}s" if f < 180 else f"{f / 60:.1f}min"


def _node_line(summary: dict) -> str:
    items = list(summary["by_node"].items())[:4]
    if not items:
        return ""
    body = "；".join("%s %.2fh/%s" % (k, v["cpu_hours"], _fmt_pct(v["share"])) for k, v in items)
    return "（按节点：%s）" % body


def render_markdown(m: dict, *, window_label: str = "", gate: dict | None = None) -> str:
    s = m["summary"]
    q = m["queue"]
    by_pl = s["by_placement"]
    lines = [
        BEGIN,
        "## 计算调度与计量（machine-generated）",
        "",
        f"- 策略版本：`{m['policy_version']}`　窗口：{window_label or '全部账本'}"
        f"　生成时间：{m['generated_at'][:19]}Z",
        f"- 账本规模：{s['jobs']} 行 / {s['total_cpu_hours']:.2f} CPU·h"
        f"（其中带策略版本 {m['governed_rows']} 行）",
        "",
        "### ① 放置分布（cpu_seconds × placement）",
        "",
        "| placement | 作业数 | CPU·h | 占比 |",
        "|---|---:|---:|---:|",
        f"| local（99 控制节点） | {by_pl['local']['jobs']} | {by_pl['local']['cpu_hours']:.2f} "
        f"| {_fmt_pct(by_pl['local']['share'])} |",
        f"| cluster（n315/n330） | {by_pl['cluster']['jobs']} | {by_pl['cluster']['cpu_hours']:.2f} "
        f"| {_fmt_pct(by_pl['cluster']['share'])} |",
        "",
        f"**本机占比 {_fmt_pct(s['local_share'])} vs 目标 ≤{_fmt_pct(m['local_share_target'])}**"
        + _node_line(s),
        "",
        "### ② 队列（调度器视角）",
        "",
        "| 指标 | 值 |",
        "|---|---|",
        f"| 队列深度 | {q['depth']} |",
        f"| 在跑 | {q['running']} |",
        f"| 最老排队 | {_fmt_s(q['oldest_queued_wait_seconds'])} |",
        f"| 等待分位（n={q['wait_n']}） | p50 {_fmt_s(q['wait_p50_seconds'])} / "
        f"p90 {_fmt_s(q['wait_p90_seconds'])} / p99 {_fmt_s(q['wait_p99_seconds'])} / "
        f"max {_fmt_s(q['wait_max_seconds'])} |",
        f"| 近 1h 派发 / 终态 | {q['dispatched_last_hour']} / {q['terminal_last_hour']} |",
        "| 排空时间估算 | %s |" % (
            "—（近 1h 零派发）" if q["drain_hours_estimate"] is None
            else "%.1f h" % q["drain_hours_estimate"]),
        f"| 队头阻塞疑似 | {'是' if q['hol_suspect'] else '否'} |",
        "",
        "### ③ 违例",
        "",
    ]
    if m["violations"]:
        lines += ["| code | 级别 | 数量 | 说明 |", "|---|---|---:|---|"]
        for v in m["violations"]:
            lines.append(f"| `{v['code']}` | {v['severity']} | {v.get('count')} | {v['detail']} |")
    else:
        lines.append("无违例。")
    lines += ["", "### ④ 每单计量（Top 5）", "",
              "| mission | CPU·h | local | cluster | 节点 |", "|---|---:|---:|---:|---|"]
    for p in m["per_mission"][:5]:
        lines.append(f"| {p['mission_id']} | {p['cpu_hours']:.3f} | {p['local_cpu_seconds']:.0f}s "
                     f"| {p['cluster_cpu_seconds']:.0f}s | {','.join(map(str, p['nodes'][:3])) or '-'} |")
    if gate:
        lines += ["", f"**门判**: `{gate['verdict']}`（exit {gate['exit_code']}）"
                      + ("；".join([" "] + gate["reasons"]) if gate["reasons"] else "")]
    lines.append(END)
    return "\n".join(lines) + "\n"