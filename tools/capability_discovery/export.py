"""导出层：把自动登记的能力灌进既有的 capability_upgrade 自动升级管线（C7）。

两件产物
--------
``registry``
    升级管线吃的**注册表文档**（``capabilities`` + ``criteria``）。自动登记发现
    的每个能力变成一个 slot（``initial_level`` = 本次定级），并附一条由证据形态
    **派生**的验收判据（不是写死的阈值）。文档可直接被
    ``tools.capability_upgrade.registry.load_registry`` / ``apply_registry`` 消费。

``evidence``
    与判据同构的证据条目（``kind = "test_outcome"``，``metrics`` = 通过/失败/跳过
    计数，``source`` 带 ``path`` + ``sha256``），灌进升级管线的 ``ingest`` 即可
    让等级沿判据机读上升，无需人工抄录。

零领域语义：判据字段全部是通用证据 grammar 的字段名，没有任何领域词条或阈值。
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from .model import CapabilityFeature, Grade, digest, level_rank

UPGRADE_REGISTRY_SCHEMA = "capability_upgrade.registry.v1"
UPGRADE_EVIDENCE_SCHEMA = "capability_upgrade.evidence_feed.v1"
EVIDENCE_KIND = "test_outcome"


def build_upgrade_registry(
    features: List[CapabilityFeature],
    grades: Dict[str, Grade],
    note: str = "",
    target_level: str = "REAL",
) -> Dict[str, Any]:
    """能力特征 + 定级 → capability_upgrade 注册表文档。"""
    caps: List[Dict[str, Any]] = []
    criteria: List[Dict[str, Any]] = []
    for feat in sorted(features, key=lambda f: f.capability_id):
        grade = grades[feat.capability_id]
        caps.append(
            {
                "capability_id": feat.capability_id,
                "label": feat.label,
                "initial_level": grade.level,
                "metadata": {
                    "origin": "capability_discovery",
                    "outcome_state": grade.outcome_state,
                    "declared_level": feat.declared_level,
                    "anchors": feat.anchors,
                    "params": feat.params,
                    "marker_formats": feat.marker_formats,
                    "tests": [t["nodeid"] for t in feat.tests],
                    "confidence": grade.confidence,
                    "policy_digest": grade.policy_digest,
                    "evidence_fingerprint": feat.evidence_fingerprint(),
                },
            }
        )
        criteria.append(
            {
                "criterion_id": f"crit.auto.{feat.capability_id}.{target_level.lower()}",
                "capability_id": feat.capability_id,
                "target_level": target_level,
                "description": (
                    "auto-derived from pytest capability-marker evidence: "
                    ">=1 passing test node carrying a source sha256"
                ),
                "spec": {
                    "evidence_kinds": [EVIDENCE_KIND],
                    "min_matching": 1,
                    "min_sources": 1,
                    "require_source_sha256": True,
                    "forbid_observed_levels": ["MOCK", "STUB", "NOT_SUPPORTED"],
                    "metrics": [{"name": "passed", "op": ">=", "value": 1, "agg": "min"}],
                },
            }
        )
    return {
        "schema": UPGRADE_REGISTRY_SCHEMA,
        "title": "auto-discovered capabilities (tools/capability_discovery)",
        "note": note
        or (
            "Generated by capability_discovery export; zero domain vocabulary — "
            "capability ids/labels/anchors came from the source test suites' own markers."
        ),
        "generator": {"pipeline": "capability_discovery", "registry_digest": digest(caps)},
        "capabilities": caps,
        "criteria": criteria,
    }


def build_upgrade_evidence(
    features: List[CapabilityFeature], grades: Dict[str, Grade]
) -> Dict[str, Any]:
    """能力特征 + 定级 → 升级管线证据 feed（每条能力一条 test_outcome 证据）。"""
    items: List[Dict[str, Any]] = []
    for feat in sorted(features, key=lambda f: f.capability_id):
        grade = grades[feat.capability_id]
        src = next((s for s in feat.sources if s.get("sha256")), None)
        if src is None:
            continue  # 无来源 sha256 的证据不入 feed（判据会把它挡在门外）
        nodeids = [t["nodeid"] for t in feat.tests]
        body = {
            "capability_id": feat.capability_id,
            "kind": EVIDENCE_KIND,
            "metrics": {
                "passed": int(feat.outcomes.get("passed", 0)),
                "failed": int(feat.outcomes.get("failed", 0)),
                "error": int(feat.outcomes.get("error", 0)),
                "skipped": int(feat.outcomes.get("skipped", 0)),
                "xfailed": int(feat.outcomes.get("xfailed", 0)),
                "xpassed": int(feat.outcomes.get("xpassed", 0)),
                "tests": feat.total_tests,
            },
            "observed_level": grade.level,
            "source": {
                "path": src["path"],
                "sha256": src["sha256"],
                "locator": ",".join(nodeids),
            },
            "payload": {
                "declared_level": feat.declared_level,
                "anchors": feat.anchors,
                "marker_formats": feat.marker_formats,
                "policy_digest": grade.policy_digest,
                "reasons": grade.reasons,
            },
        }
        body["evidence_id"] = f"ev-{digest(body)[:16]}"
        items.append(body)
    return {
        "schema": UPGRADE_EVIDENCE_SCHEMA,
        "title": "evidence feed derived from pytest capability markers",
        "items": items,
    }


def export(
    features: List[CapabilityFeature],
    grades: Dict[str, Grade],
    registry_path: Optional[Path | str] = None,
    evidence_path: Optional[Path | str] = None,
    note: str = "",
    target_level: str = "REAL",
) -> Dict[str, Any]:
    """导出两份文档；返回 (registry, evidence) 供调用方直接用。"""
    registry = build_upgrade_registry(features, grades, note=note, target_level=target_level)
    evidence = build_upgrade_evidence(features, grades)
    for path, doc in ((registry_path, registry), (evidence_path, evidence)):
        if path is None:
            continue
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    return {"registry": registry, "evidence": evidence}


def validate_with_upgrade_pipeline(registry_doc: Dict[str, Any]) -> Dict[str, Any]:
    """用升级管线自己的加载器校验导出文档（C7 的机器可算证明）。

    延迟 import：本模块不把 capability_upgrade 变成硬依赖，
    但校验时一定走**对方**的代码路径，而不是自己写的宽松校验。
    """
    from tools.capability_upgrade.registry import apply_registry, load_registry
    from tools.capability_upgrade.store import Store

    tmp = Path(__file__).resolve().parents[2] / "artifacts" / "capability_discovery" / "_validate_registry.json"
    tmp.parent.mkdir(parents=True, exist_ok=True)
    tmp.write_text(json.dumps(registry_doc, indent=2, sort_keys=True, ensure_ascii=False), encoding="utf-8")
    try:
        doc = load_registry(tmp)  # 对方的校验器：id 唯一、判据指向已知能力
        store = Store(":memory:")
        try:
            counts = apply_registry(store, doc)  # 建 slot + criterion
            slots = [s.capability_id for s in store.list_slots()]
            crits = [c.capability_id for s in store.list_slots() for c in store.list_criteria(s.capability_id)]
        finally:
            store.close()
    finally:
        tmp.unlink(missing_ok=True)
    return {
        "ok": True,
        "slots_applied": int(counts.get("slots", 0)),
        "criteria_applied": int(counts.get("criteria", 0)),
        "slot_ids": slots,
        "criteria_for": crits,
    }


def max_export_level(features: List[CapabilityFeature], grades: Dict[str, Grade]) -> int:
    """辅助：导出批次里的最高等级序（报告用）。"""
    return max((level_rank(grades[f.capability_id].level) for f in features), default=0)