"""Synthetic labelled corpus: proposal/report pairs with *construction-time* labels.

Why synthetic + real-text mutation (two corpora, not one)
---------------------------------------------------------
A rule-based detector can be made to look perfect on data generated by the same
grammar it reads.  So the evaluator uses two independent corpora:

1. **Synthetic** (this module): paraphrased, unit-reformatted, reordered text with
   injected narrowings *and* hard negatives (5-10% relaxation, declared waivers,
   benign re-formats).  Labels come from the generator, never from the detector.
2. **Real-text mutation** (``real_corpus.py``): criteria harvested from
   ``data/campaigns/*/nodes.json`` (human-written, real platform campaign), then
   mutated by construction.  This measures external validity of the parser and
   comparator on text nobody designed for it.

Ground truth rules (identical to the audited policy, so labels are not
detector-dependent): a criterion is *drift* iff threshold relaxation > 0.10, or
operator downgrade, or undeclared drop, or measurement-kind swap, or tolerance
widening > 10%.  A drop covered by a waiver carrying both ``reason`` and
``approved_by`` is *not* drift.
"""
from __future__ import annotations

import math
import random
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Sequence, Tuple

from . import model

