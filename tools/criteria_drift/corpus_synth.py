OPS_UPPER = ("≤", "<=", "不超过", "at most")
OPS_LOWER = ("≥", ">=", "不低于", "at least")


@dataclass
class CriterionCase:
    index: int
    kind: str
    subject_zh: str
    subject_en: str
    op: str
    value: float                    # canonical
    unit: str
    tolerance: Optional[float]      # canonical (proposal)
    proposal_text: str
    report_text: str
    mutation: str = "none"
    relax_delta: Optional[float] = None
    label_drift: bool = False
    label_reason: str = ""


@dataclass
class DocCase:
    doc_id: str
    proposal: List[str]
    report: List[str]
    waivers: List[Dict[str, str]]
    criteria: List[CriterionCase]
    doc_label: bool
    regime: str
    seed: int


def _fmt_num(x: float, unit: str) -> Tuple[str, str]:
    """Number + unit suffix for rendering; unit suffix empty for bare ratios."""
    if unit == model.UNIT_FRACTION:
        pct = x * 100.0
        if pct >= 1.0:
            s = f"{pct:.3g}"
        elif pct >= 0.01:
            s = f"{pct:.3g}"
        else:
            return f"{x:.3g}", ""
        return s, "%"
    if unit == model.UNIT_COUNT:
        return f"{int(round(x))}", "例"
    if unit == model.UNIT_ORDER:
        return f"{x:g}", "阶"
    return f"{x:g}", ""


def _baseline_value(kind: str, rng: random.Random) -> Tuple[float, str, str]:
    if kind == model.KIND_ERROR:
        return rng.choice([0.005, 0.01, 0.02, 0.03, 0.05]), model.UNIT_FRACTION, "<="
    if kind == model.KIND_CONSERVATION:
        if rng.random() < 0.6:
            return rng.choice([1e-12, 1e-10, 1e-9]), model.UNIT_DIMENSIONLESS, "<="
        return rng.choice([0.001, 0.005, 0.01]), model.UNIT_FRACTION, "<="
    if kind == model.KIND_ORDER:
        return rng.choice([1.5, 1.8, 2.0, 2.5]), model.UNIT_ORDER, ">="
    if kind == model.KIND_PVALUE:
        return rng.choice([0.01, 0.05]), model.UNIT_PVALUE, ">="
    if kind == model.KIND_COVERAGE:
        return rng.choice([0.70, 0.80, 0.90, 0.95]), model.UNIT_FRACTION, ">="
    if kind == model.KIND_COUNT:
        return float(rng.choice([6, 10, 12, 15, 20])), model.UNIT_COUNT, ">="
    if kind == model.KIND_THRESHOLD:
        if rng.random() < 0.5:
            return rng.choice([0.99, 0.999, 0.9999]), model.UNIT_DIMENSIONLESS, ">="
        return rng.choice([0.01, 0.05, 0.1]), model.UNIT_FRACTION, "<="
    raise ValueError(kind)


def _render(rng: random.Random, subject_zh: str, subject_en: str, op: str,
            value: float, unit: str, style: str = "mixed", tolerance: Optional[float] = None) -> str:
    """Render a criterion in one of several interchangeable surface forms."""
    upper = model.operator_direction(op) == "upper"
    strict = op in ("<", ">")
    # strictness must survive rendering: a "<" rendered as "<=" would silently
    # change the ground truth of an operator-downgrade case
    if style == "zh":
        if upper:
            op_txt = rng.choice(["低于", "小于"]) if strict else rng.choice(["≤", "不超过", "至多"])
        else:
            op_txt = rng.choice(["高于", "大于"]) if strict else rng.choice(["≥", "不低于", "至少"])
        num, suf = _fmt_num(value, unit)
        text = f"{subject_zh}{op_txt}{num}{suf}"
    elif style == "en":
        op_txt = {True: ("<" if strict else "<="), False: (">" if strict else ">=")}[upper]
        num, suf = _fmt_num(value, unit)
        text = f"{subject_en} {op_txt} {num}{suf}"
    else:
        if upper:
            op_glyph = "<" if strict else rng.choice(["≤", "<="])
        else:
            op_glyph = ">" if strict else rng.choice(["≥", ">="])
        num, suf = _fmt_num(value, unit)
        text = f"{subject_zh} {op_glyph} {num}{suf}"
    if tolerance is not None:
        tol_num, tol_suf = _fmt_num(tolerance, model.UNIT_FRACTION if unit == model.UNIT_FRACTION else unit)
        text += f"±{tol_num}{tol_suf}"
    return text


def _benign_reformat(rng: random.Random, case: CriterionCase) -> str:
    """Meaning-preserving surface change: unit scale, operator spelling,
    whitespace, language.  Must never be flagged."""
    op = case.op
    value = case.value
    unit = case.unit
    style = rng.choice(["zh", "en", "mixed"])
    show_ratio = False
    if unit == model.UNIT_FRACTION and rng.random() < 0.4:
        show_ratio = True
    if unit == model.UNIT_COUNT and rng.random() < 0.5:
        op = op
    if show_ratio:
        subject = rng.choice([case.subject_zh, case.subject_en])
        upper = model.operator_direction(op) == "upper"
        strict = op in ("<", ">")
        op_txt = (("<" if strict else "<=") if upper else (">" if strict else ">="))
        text = f"{subject} {op_txt} {value:.4g}"
        if case.tolerance is not None:
            # dropping the band would itself be a real narrowing; a *benign*
            # re-format must carry it over in the new scale
            text += f"±{case.tolerance:.4g}"
    else:
        text = _render(rng, case.subject_zh, case.subject_en, op, value, unit,
                       style=style, tolerance=case.tolerance)
    if rng.random() < 0.25:
        text = text.replace(" ", "  ")
    return text


def parsed_relaxation(proposal_text: str, report_text: str) -> Optional[float]:
    """Relaxation actually written in the two artifacts (canonical units).

    Labels are derived from the rendered text, not from the pre-rounding number:
    a count relaxed from 20 to 18 is a 10% relaxation, and the label must say so
    no matter what the generator intended before rounding.
    """
    from .parser import parse_with_cn_order
    from .compare import relaxation_ratio
    a = parse_with_cn_order(proposal_text)
    b = parse_with_cn_order(report_text)
    if a.value is None or b.value is None:
        return None
    return relaxation_ratio(a, b)


def _relaxed_value(rng: random.Random, op: str, value: float, unit: str) -> Tuple[float, float]:
    """Return (new_value, relaxation_ratio_as_defined_by_policy)."""
    if unit == model.UNIT_COUNT:
        factor = rng.uniform(1.05, 1.35)
        if model.operator_direction(op) == "upper":
            new = value * factor
        else:
            new = value / factor
        return float(max(1, round(new))), (new - value) / value if model.operator_direction(op) == "upper" else (value - new) / value
    factor = rng.uniform(1.05, 1.16) if rng.random() < 0.6 else rng.uniform(0.95, 1.10)
    if model.operator_direction(op) == "upper":
        new = value * factor
        return new, (new - value) / abs(value)
    new = value / factor if factor > 1 else value * factor
    return new, (value - new) / abs(value)


def _pick_subjects(rng: random.Random, kinds: Sequence[str]) -> List[Tuple[str, str, str]]:
    out = []
    for k in kinds:
        pool = SUBJECTS[k]
        out.append(rng.choice(pool))
    return out


def generate_corpus(n_docs: int = 240, seed: int = 20261111) -> List[DocCase]:
    rng = random.Random(seed)
    docs: List[DocCase] = []
    kind_menu = list(SUBJECTS.keys())
    for d in range(n_docs):
        regime = "clean" if rng.random() < 0.5 else "drift"
        k = rng.randint(4, 6)
        kinds = rng.sample(kind_menu, k)
        subjects = _pick_subjects(rng, kinds)
        cases: List[CriterionCase] = []
        proposal: List[str] = []
        report: List[str] = []
        waivers: List[Dict[str, str]] = []

        for idx, (kind, (zh, en, para)) in enumerate(zip(kinds, subjects)):
            value, unit, op = _baseline_value(kind, rng)
            tolerance = None
            if unit == model.UNIT_FRACTION and kind in (model.KIND_ERROR, model.KIND_THRESHOLD) and rng.random() < 0.25:
                tolerance = round(value * rng.choice([0.05, 0.1, 0.2]), 6)
            strict_proposal = rng.random() < 0.12
            if strict_proposal and op in ("<=", ">=") and kind != model.KIND_COUNT:
                op = "<" if op == "<=" else ">"
            ptext = _render(rng, zh, en, op, value, unit,
                            style=rng.choice(["zh", "en", "mixed"]), tolerance=tolerance)
            case = CriterionCase(index=idx, kind=kind, subject_zh=zh, subject_en=en, op=op,
                                 value=value, unit=unit, tolerance=tolerance,
                                 proposal_text=ptext, report_text="")
            cases.append(case)
            proposal.append(ptext)
            report.append("")

        # report side: benign re-format / paraphrase first
        for case in cases:
            case.report_text = _benign_reformat(rng, case)

        # mutations
        if regime == "drift":
            n_mut = rng.randint(1, min(3, len(cases)))
            chosen = rng.sample(range(len(cases)), n_mut)
            for ci in chosen:
                case = cases[ci]
                mut = rng.choices(
                    ["relax", "relax_mild", "op_down", "drop", "waiver_drop", "kind_swap", "tol_widen"],
                    weights=[0.26, 0.12, 0.12, 0.16, 0.10, 0.10, 0.14],
                )[0]
                if mut == "op_down" and not (case.op in ("<", ">") and case.unit != model.UNIT_COUNT):
                    mut = "relax"
                if mut == "tol_widen" and case.tolerance is None:
                    mut = "relax"
                case.mutation = mut
                if mut == "relax":
                    new_val, delta = _relaxed_value(rng, case.op, case.value, case.unit)
                    case.report_text = _render(rng, case.subject_zh, case.subject_en, case.op,
                                               new_val, case.unit, style=rng.choice(["zh", "mixed"]),
                                               tolerance=case.tolerance)
                    delta = parsed_relaxation(case.proposal_text, case.report_text)
                    if delta is None:
                        delta = 0.0
                    case.relax_delta = delta
                    case.label_drift = delta > 0.10
                    case.label_reason = f"relax delta(rendered)={delta:.4f}"
                elif mut == "relax_mild":
                    factor = rng.uniform(0.96, 1.099)
                    new_val = case.value * factor if model.operator_direction(case.op) == "upper" else case.value * factor
                    case.report_text = _render(rng, case.subject_zh, case.subject_en, case.op,
                                               new_val, case.unit, style="mixed", tolerance=case.tolerance)
                    delta = parsed_relaxation(case.proposal_text, case.report_text)
                    if delta is None:
                        delta = 0.0
                    case.relax_delta = delta
                    case.label_drift = delta > 0.10
                    case.label_reason = f"mild relax delta(rendered)={delta:.4f}"
                elif mut == "op_down":
                    new_op = "<=" if case.op == "<" else ">="
                    case.report_text = _render(rng, case.subject_zh, case.subject_en, new_op,
                                               case.value, case.unit, style="mixed", tolerance=case.tolerance)
                    case.label_drift = True
                    case.label_reason = f"operator {case.op}->{new_op}"
                elif mut == "drop":
                    case.report_text = ""
                    case.label_drift = True
                    case.label_reason = "dropped without waiver"
                elif mut == "waiver_drop":
                    case.report_text = ""
                    case.label_drift = False
                    case.label_reason = "dropped with declared waiver"
                    waivers.append({
                        "criterion": case.proposal_text,
                        "reason": rng.choice([
                            "测量口径升级，旧判据不可直接复算",
                            "参考值来源更新，需换锚后重测",
                        ]),
                        "approved_by": rng.choice(["reviewer-A", "reviewer-B", "gate-owner"]),
                    })
                elif mut == "kind_swap":
                    used_kinds = {c.kind for c in cases}
                    available = [kk for kk in kind_menu if kk not in used_kinds]
                    if not available:
                        mut = "relax"
                        case.mutation = mut
                        new_val, _ = _relaxed_value(rng, case.op, case.value, case.unit)
                        case.report_text = _render(rng, case.subject_zh, case.subject_en, case.op,
                                                   new_val, case.unit, style="zh", tolerance=case.tolerance)
                        delta = parsed_relaxation(case.proposal_text, case.report_text) or 0.0
                        case.relax_delta = delta
                        case.label_drift = delta > 0.10
                        case.label_reason = f"relax delta(rendered)={delta:.4f}"
                        continue
                    other_kind = rng.choice(available)
                    zh2, en2, _ = rng.choice(SUBJECTS[other_kind])
                    v2, u2, o2 = _baseline_value(other_kind, rng)
                    case.report_text = _render(rng, zh2, en2, o2, v2, u2, style="mixed")
                    case.label_drift = True
                    case.label_reason = f"kind swap {case.kind}->{other_kind}"
                elif mut == "tol_widen":
                    new_tol = case.tolerance * rng.uniform(1.4, 2.5)
                    case.report_text = _render(rng, case.subject_zh, case.subject_en, case.op,
                                               case.value, case.unit, style="mixed", tolerance=new_tol)
                    case.label_drift = True
                    case.label_reason = f"tolerance {case.tolerance}->{new_tol:.4g}"

        # assemble report (drops removed), then reorder (order must not matter)
        report_texts = [c.report_text for c in cases if c.report_text]
        rng.shuffle(report_texts)
        doc_label = any(c.label_drift for c in cases)
        docs.append(DocCase(
            doc_id=f"syn-{d:04d}", proposal=[c.proposal_text for c in cases], report=report_texts,
            waivers=waivers, criteria=cases, doc_label=doc_label, regime=regime, seed=seed,
        ))
    return docs


def to_documents(doc: DocCase) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    prop = {"acceptance_criteria": list(doc.proposal)}
    rep = {"acceptance_criteria": list(doc.report)}
    if doc.waivers:
        rep["waivers"] = list(doc.waivers)
    return prop, rep