"""Fail-closed matrix: every "cannot reason statically" situation must fall back
to the full suite (criterion C3: 10 classes, 10/10 fall back).

The matrix is built on the synthetic tree of :mod:`sandbox` (zero domain
semantics) and each scenario is materially independent: a fresh copy of the tree
is mutated, the graph is built, and the selector is asked for a decision.
"""

from __future__ import annotations

import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence

from .config import SelectorConfig
from .graph import ImportGraph
from .sandbox import copy_tree, make_clean_tree, touch
from .selector import ImpactSelector

CLASSES_UNDER_TEST = (
    "new_file",
    "graph_incomplete",
    "dynamic_import",
    "generated_file",
    "cross_repo_ref",
    "outside_roots",
    "test_infra",
    "non_code_asset",
    "deleted_module",
    "mass_change",
)

_BROKEN = 'def oops(:\n    return 1\n'
_DYN = (
    'import importlib\n\nimport alpha.core\n\n\n'
    'def load(name: str):\n    return importlib.import_module(name)\n\n\n'
    'def run() -> int:\n    return alpha.core.Engine().run(1)\n'
)


@dataclass
class Scenario:
    name: str
    expect: str
    prep: Optional[Callable[[Path], None]] = None
    mutate: Optional[Callable[[Path], List[str]]] = None


def _prep_broken(root: Path) -> None:
    touch(root, "alpha/broken.py", _BROKEN)
    touch(root, "alpha/tests/test_broken.py", "from alpha.broken import oops\n\n\ndef test_oops():\n    assert oops()\n")


def _prep_dynamic(root: Path) -> None:
    touch(root, "alpha/dyn.py", _DYN)
    touch(root, "alpha/tests/test_dyn.py", "from alpha.dyn import run\n\n\ndef test_run():\n    assert run() == 2\n")


def _prep_generated(root: Path) -> None:
    touch(root, "alpha/schema_pb2.py", "# generated by toolchain; do not edit\nVALUE = 1\n")


def _prep_cross_repo(root: Path) -> None:
    touch(root, "alpha/remote.py", '"""Placeholder bridging to another repository."""\n\ntry:\n    import TensorFVM.solver as solver\nexcept ImportError:  # pragma: no cover\n    solver = None\n')


def _prep_conftest(root: Path) -> None:
    touch(root, "alpha/tests/conftest.py", '"""Shared fixtures."""\n')


def _prep_asset(root: Path) -> None:
    touch(root, "alpha/data/fixtures.json", "{}\n")


def _prep_mass(root: Path) -> None:
    for i in range(30):
        touch(root, f"alpha/mass/mod_{i:02d}.py", f'"""Placeholder {i}."""\n\nVALUE = {i}\n')


def _mutate_mass(root: Path) -> List[str]:
    out = []
    for i in range(30):
        rel = f"alpha/mass/mod_{i:02d}.py"
        touch(root, rel, f'"""Placeholder {i} (changed)."""\n\nVALUE = {i + 1}\n')
        out.append(rel)
    return out


def _mutate_delete_util(root: Path) -> List[str]:
    (root / "alpha" / "util.py").unlink()
    return ["alpha/util.py"]


def _prep_no_tests(root: Path) -> None:
    for d in ("alpha/tests", "tests", "beta/tests"):
        for p in sorted((root / d).glob("*.py")):
            p.unlink()


def _mutate_asset(root: Path) -> List[str]:
    touch(root, "alpha/data/fixtures.json", '{"changed": true}\n')
    return ["alpha/data/fixtures.json"]


def _mutate_new_file(root: Path) -> List[str]:
    touch(root, "alpha/newness.py", '"""Brand new module."""\n\nVALUE = 1\n')
    return ["alpha/newness.py"]


def _mutate_static(root: Path) -> List[str]:
    return ["alpha/core.py"]


SCENARIOS: Sequence[Scenario] = (
    Scenario("new_file", "new_file", None, _mutate_new_file),
    Scenario("graph_incomplete", "graph_incomplete", _prep_broken, _mutate_static),
    Scenario("dynamic_import", "dynamic_import", _prep_dynamic, _mutate_static),
    Scenario("generated_file", "generated_file", _prep_generated, lambda r: ["alpha/schema_pb2.py"]),
    Scenario("cross_repo_ref", "cross_repo_ref", _prep_cross_repo, lambda r: ["alpha/remote.py"]),
    Scenario("outside_roots", "outside_roots", None, lambda r: ["../outside/file.py"]),
    Scenario("test_infra", "test_infra", _prep_conftest, lambda r: ["alpha/tests/conftest.py"]),
    Scenario("non_code_asset", "non_code_asset", _prep_asset, _mutate_asset),
    Scenario("deleted_module", "deleted_module", None, _mutate_delete_util),
    Scenario("mass_change", "mass_change", _prep_mass, _mutate_mass),
    Scenario("unknown_change_kind", "unknown_change_kind", None, lambda r: ["alpha/absent.py"]),
    Scenario("safety_missing", "safety_missing", _prep_no_tests, _mutate_static),
)

CONTROL_SCENARIO = "control_subset"
CONTROL_DOCS = "control_docs_only"


def run_matrix(config: SelectorConfig | None = None, keep_root: Path | str | None = None) -> Dict[str, object]:
    cfg = config or SelectorConfig()
    rows: List[dict] = []
    base = Path(keep_root) if keep_root else Path(tempfile.mkdtemp(prefix="tis-matrix-"))
    template = make_clean_tree(base / "_template")

    # control: a plain static change on a clean tree must produce a *subset*
    work = copy_tree(template, base / "control")
    graph = ImportGraph.build(work, use_history=False, jobs=1, use_references=True)
    selector = ImpactSelector(graph, cfg, root=work)
    sel = selector.select(["alpha/util.py"], mode="enforcing")
    rows.append(
        {
            "name": CONTROL_SCENARIO,
            "expected": "subset",
            "actual": sel.mode,
            "trigger": sel.trigger,
            "selected": len(sel.tests),
            "tests": sel.tests,
            "ok": sel.mode == "subset" and len(sel.tests) >= 1,
        }
    )

    # control 2: documentation-only change must still run >= 1 safety test (C4)
    work = copy_tree(template, base / "docs_only")
    graph = ImportGraph.build(work, use_history=False, jobs=1, use_references=True)
    selector = ImpactSelector(graph, cfg, root=work)
    sel = selector.select(["docs/guide.md"], mode="enforcing")
    rows.append(
        {
            "name": "control_docs_only",
            "expected": "subset>=1",
            "actual": sel.mode,
            "trigger": sel.trigger,
            "selected": len(sel.tests),
            "tests": sel.tests,
            "ok": sel.mode == "subset" and len(sel.tests) >= 1,
        }
    )

    for sc in SCENARIOS:
        work = copy_tree(template, base / sc.name)
        if sc.prep:
            sc.prep(work)
        graph = ImportGraph.build(work, use_history=False, jobs=1, use_references=True)
        selector = ImpactSelector(graph, cfg, root=work)
        changed = sc.mutate(work) if sc.mutate else []
        sel = selector.select(changed, mode="enforcing")
        rows.append(
            {
                "name": sc.name,
                "expected": sc.expect,
                "actual": sel.trigger or sel.mode,
                "trigger": sel.trigger,
                "mode": sel.mode,
                "selected": len(sel.tests),
                "all_tests": sel.all_tests,
                "reasons": sel.reasons[:3],
                "ok": sel.mode == "full" and (sel.trigger or "").startswith(sc.expect),
            }
        )

    core = [r for r in rows if r["name"] in CLASSES_UNDER_TEST]
    passed_core = sum(1 for r in core if r["ok"])
    return {
        "schema": "tp.test_impact_selector.failclosed_matrix/v1",
        "classes_total": len(core),
        "classes_fail_closed": passed_core,
        "verdict": f"{passed_core}/{len(core)}",
        "criterion_C3": passed_core == len(core),
        "rows": rows,
        "root": str(base),
    }