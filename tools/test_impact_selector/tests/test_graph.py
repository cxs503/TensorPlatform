"""Unit tests: graph construction (import shapes that break naive scanners)."""

from __future__ import annotations

from pathlib import Path

import pytest

from tools.test_impact_selector.graph import ImportGraph, cocchange_edges, scan_file
from tools.test_impact_selector.sandbox import make_clean_tree, touch


@pytest.fixture()
def tree(tmp_path: Path) -> Path:
    return make_clean_tree(tmp_path / "repo")


def _graph(root: Path, **kw) -> ImportGraph:
    return ImportGraph.build(root, use_history=False, jobs=1, **kw)


def test_relative_and_reexport_edges(tree: Path):
    g = _graph(tree)
    # re-export: alpha/__init__.py imports alpha/core.py
    assert "alpha/core.py" in g.deps("alpha/__init__.py")
    # `from alpha.core import Engine` resolves to the module file
    assert "alpha/core.py" in g.deps("alpha/tests/test_core.py")


def test_submodule_and_ancestor_edges(tree: Path):
    g = _graph(tree)
    deps = g.deps("alpha/tests/test_core.py")
    # ancestors always execute: package __init__ files are dependencies too
    assert "alpha/__init__.py" in deps
    assert "alpha/tests/__init__.py" in deps


def test_conditional_import_is_kept_and_flagged(tree: Path):
    g = _graph(tree)
    node = g.nodes["alpha/extra.py"]
    assert "alpha/util.py" in node.imports  # try/except ImportError still an edge
    assert "alpha/util.py" in node.conditional  # ... but flagged conditional


def test_impact_is_reverse_transitive(tree: Path):
    g = _graph(tree)
    impacted = g.impact(["alpha/core.py"])
    assert "alpha/tests/test_core.py" in impacted
    assert "tests/test_smoke_all.py" in impacted
    assert "beta/tests/test_calc_0.py" not in impacted


def test_literal_reference_edge_for_subprocess_usage(tree: Path):
    g = _graph(tree)
    # test_cli_ref.py mentions "alpha.util" only inside a string (python -c)
    assert "alpha/tests/test_cli_ref.py" in g.impact(["alpha/util.py"])


def test_dynamic_and_generated_flags(tree: Path):
    touch(tree, "alpha/dyn.py", "import importlib\n\n\ndef load(n):\n    return importlib.import_module(n)\n")
    touch(tree, "alpha/plugin_host.py", "import importlib\n\n\ndef load():\n    return importlib.import_module('alpha.util')\n")
    touch(tree, "alpha/schema_pb2.py", "# generated by toolchain\nVALUE = 1\n")
    touch(
        tree,
        "alpha/lazy.py",
        "import importlib\n\n\ndef __getattr__(name):\n    return importlib.import_module(name)\n",
    )
    g = _graph(tree)
    assert g.nodes["alpha/dyn.py"].dynamic is True
    assert g.nodes["alpha/lazy.py"].dynamic is True  # PEP 562 lazy import
    assert g.nodes["alpha/schema_pb2.py"].generated is True
    assert g.nodes["alpha/core.py"].generated is False
    # a literal import-machinery target is a *resolvable* edge, not a blind spot
    assert g.nodes["alpha/plugin_host.py"].dynamic is False
    assert "alpha/util.py" in g.deps("alpha/plugin_host.py")


def test_parse_error_recorded_not_raised(tree: Path):
    touch(tree, "alpha/broken.py", "def oops(:\n    pass\n")
    g = _graph(tree)
    assert g.nodes["alpha/broken.py"].parse_error
    assert g.stats()["parse_errors"] == 1


def test_cross_repo_reference_marked(tree: Path):
    touch(tree, "alpha/remote.py", "import TensorFVM.solver\n")
    g = _graph(tree)
    assert g.nodes["alpha/remote.py"].cross_repo
    assert "TensorFVM.solver" in g.nodes["alpha/remote.py"].cross_repo


def test_fingerprint_is_deterministic(tree: Path):
    a = _graph(tree).fingerprint
    b = _graph(tree).fingerprint
    assert a == b
    touch(tree, "alpha/newness.py", '"""new."""\nVALUE = 2\n')
    assert _graph(tree).fingerprint != a


def test_scan_cache_roundtrip(tree: Path, tmp_path: Path):
    cache = tmp_path / "cache" / "scans.json"
    g1 = ImportGraph.build(tree, use_history=False, jobs=1, cache_path=cache)
    assert g1.build_report.cache_hits == 0
    g2 = ImportGraph.build(tree, use_history=False, jobs=1, cache_path=cache)
    assert g2.build_report.cache_hits == g1.build_report.files
    assert g2.fingerprint == g1.fingerprint


def test_cocchange_edges_from_history(tree: Path):
    from tools.test_impact_selector.sandbox import git_init

    git_init(tree)
    # one commit only -> support 1 -> no edge (support threshold protects us)
    assert cocchange_edges(tree, max_commits=50) == {}
    from tools.test_impact_selector.sandbox import git_commit

    src = tree / "alpha" / "core.py"
    src.write_text(src.read_text() + "\n# touch\n")
    tst = tree / "alpha" / "tests" / "test_core.py"
    tst.write_text(tst.read_text() + "\n# touch\n")
    git_commit(tree, "second")
    table = cocchange_edges(tree, max_commits=50)
    assert table.get("alpha/core.py") == {"alpha/tests/test_core.py"}


def test_scan_file_reports_generated_and_dynamic(tmp_path: Path):
    p = tmp_path / "mod.py"
    p.write_text("import importlib\n\n\ndef f(name):\n    return importlib.import_module(name)\n")
    rel, rec = scan_file((str(tmp_path), "mod.py"))
    assert rel == "mod.py"
    assert rec["dynamic"] is True
    # only the third party module name is recorded, no in-repo edge
    assert [imp[0] for imp in rec["imports"]] == ["importlib"]
    assert rec["generated"] is False