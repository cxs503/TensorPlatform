def is_test_path(rel_path: str) -> bool:
    """Mirror of pytest's default collection (plus this repo's conventions).

    ``conftest.py`` and private helpers (``_*.py``) are *test infrastructure*,
    not tests: they are handled by the fail-closed ``test_infra`` class instead
    of being counted as runnable test files.
    """
    name = rel_path.rsplit("/", 1)[-1]
    if not name.endswith(".py") or name == "conftest.py" or name.startswith("_"):
        return False
    if name.startswith("test_") or name.endswith("_test.py"):
        return True
    parts = rel_path.split("/")
    return "tests" in parts[:-1]


@dataclass(frozen=True)
class SelectorConfig:
    """Policy knobs of the selector (frozen -> hashable/deterministic)."""

    # Safety net: these tests run on *every* change, whatever the impact set is.
    safety_tests: Tuple[str, ...] = (
        "tests/test_smoke_imports.py",
    )
    safety_globs: Tuple[str, ...] = ("tests/test_smoke*.py",)
    # when neither the explicit list nor the globs resolve, fall back to the
    # K tests with the widest dependency reach (mechanical, no hand picking)
    safety_reach_topk: int = 3

    # fail-closed policy
    max_changed_files: int = 25
    max_selected_ratio: float = 0.60
    empty_change_policy: str = "full"  # "full" | "safety"
    # a parse error in a module that nothing imports cannot hide impact, so it
    # is logged but does not force the full suite (leaves are still audited)
    strict_parse_errors: bool = True
    parse_error_leaves_tolerated: bool = True

    # co-change (historical) auxiliary edges
    cocchange_min_support: int = 2
    cocchange_jaccard: float = 0.25
    cocchange_max_commits: int = 400

    # shadow -> enforcing rollout
    mode: str = "shadow"  # "shadow" | "enforcing" | "off"
    shadow_min_samples: int = 200
    shadow_max_false_negative_risk: float = 0.0

    extras: Tuple[Tuple[str, str], ...] = field(default=())

    def as_dict(self) -> dict:
        return {
            "safety_tests": list(self.safety_tests),
            "safety_globs": list(self.safety_globs),
            "safety_reach_topk": self.safety_reach_topk,
            "max_changed_files": self.max_changed_files,
            "max_selected_ratio": self.max_selected_ratio,
            "empty_change_policy": self.empty_change_policy,
            "strict_parse_errors": self.strict_parse_errors,
            "parse_error_leaves_tolerated": self.parse_error_leaves_tolerated,
            "cocchange_min_support": self.cocchange_min_support,
            "cocchange_jaccard": self.cocchange_jaccard,
            "cocchange_max_commits": self.cocchange_max_commits,
            "mode": self.mode,
            "shadow_min_samples": self.shadow_min_samples,
            "shadow_max_false_negative_risk": self.shadow_max_false_negative_risk,
        }