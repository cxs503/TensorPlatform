def post(payload: dict) -> dict:
    base = os.environ["TENSOR_API_BASE"]
    user, password = os.environ["TENSOR_AGENT_USER"], os.environ["TENSOR_AGENT_PASS"]
    req = urllib.request.Request(
        base + "/auth/login",
        data=json.dumps({"username": user, "password": password}).encode(),
        headers={"Content-Type": "application/json"})
    token = json.load(urllib.request.urlopen(req))
    token = token.get("access_token") or token.get("token")
    req = urllib.request.Request(
        base + "/tensor/reports",
        data=json.dumps(payload).encode(),
        headers={"Content-Type": "application/json",
                 "Authorization": "Bearer " + token})
    try:
        return json.load(urllib.request.urlopen(req))
    except urllib.error.HTTPError as exc:  # surface the server message
        return {"error": exc.code, "body": exc.read().decode("utf-8", "ignore")[:2000]}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    with open(os.path.join(ART, "conservation_audit.json"), encoding="utf-8") as fh:
        audit = json.load(fh)
    markdown = render(audit)
    os.makedirs(DOCS, exist_ok=True)
    doc_path = os.path.join(DOCS, "P167W2B-N08_cross_library_conservation_gate.md")
    with open(doc_path, "w", encoding="utf-8") as fh:
        fh.write(markdown)
    print("wrote", doc_path, len(markdown), "chars")
    payload = build_payload(markdown)
    if args.dry_run:
        with open("/tmp/report_p167w2b_n08.json", "w", encoding="utf-8") as fh:
            json.dump({k: v for k, v in payload.items() if k != "figures"}, fh,
                      ensure_ascii=False, indent=2)
        print("dry-run: payload written to /tmp/report_p167w2b_n08.json")
        return 0
    result = post(payload)
    print(json.dumps(result, ensure_ascii=False)[:1200])
    return 0 if "error" not in result else 1


