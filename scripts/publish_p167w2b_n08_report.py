def f(x, digits: int = 3) -> str:
    """Compact scientific formatting for injected numbers."""
    if isinstance(x, bool):
        return "true" if x else "false"
    if x is None:
        return "—"
    if isinstance(x, int):
        return str(x)
    if x == 0.0:
        return "0"
    if abs(x) < 1e-3 or abs(x) >= 1e4:
        return f"{x:.{digits}e}"
    return f"{x:.{max(digits, 4)}g}"


