#!/usr/bin/env python3
"""Post the criteria-drift report (six elements + 4 embedded figures) to the platform.

Payload comes from ``artifacts/criteria_drift/report_payload.json``, which is
generated by ``tools/criteria_drift/run_audit.py`` - numbers are never typed by
hand here.
"""
from __future__ import annotations

import json
import os
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAYLOAD = ROOT / "artifacts" / "criteria_drift" / "report_payload.json"


def main() -> int:
    api_base = os.environ.get("TENSOR_API_BASE", "http://127.0.0.1:8010/api/v1").rstrip("/")
    user = os.environ.get("TENSOR_AGENT_USER", "")
    passwd = os.environ.get("TENSOR_AGENT_PASS", "")
    if not user or not passwd:
        print("missing TENSOR_AGENT_USER/PASS", file=sys.stderr)
        return 2
    payload = json.loads(PAYLOAD.read_text(encoding="utf-8"))
    # the platform accepts mission_id + figures with png_base64
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    login = urllib.request.Request(
        f"{api_base}/auth/login",
        data=json.dumps({"username": user, "password": passwd}).encode(),
        headers={"Content-Type": "application/json"},
    )
    token = json.loads(urllib.request.urlopen(login, timeout=15).read())["access_token"]
    req = urllib.request.Request(
        f"{api_base}/tensor/reports",
        data=body,
        headers={"Content-Type": "application/json", "Authorization": f"Bearer {token}"},
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        out = json.loads(resp.read().decode("utf-8"))
    print(json.dumps({"status": resp.status, "report": out}, ensure_ascii=False)[:800])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())